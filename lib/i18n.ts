export type TranslationKey = keyof typeof t['pt-PT']

export function translate(lang: Lang, key: TranslationKey): string {
  return (t[lang] as Record<string, string>)[key] ?? (t['pt-PT'] as Record<string, string>)[key] ?? key
}

export function detectLang(): Lang {
  if (typeof window === 'undefined') return 'pt-PT'
  const saved = localStorage.getItem('pg.lang') as Lang | null
  if (saved && saved in t) return saved
  const browser = navigator.language
  if (browser.startsWith('pt-BR') || browser === 'pt-BR') return 'pt-BR'
  if (browser.startsWith('pt')) return 'pt-PT'
  if (browser.startsWith('es')) return 'es'
  if (browser.startsWith('en')) return 'en'
  return 'pt-PT'
}
